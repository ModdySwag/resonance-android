#!/usr/bin/env python3
"""Pull the shell's icon set out of the local Iconset library and inline it into the shim.

Iconset (C:\\Program Files\\Iconset) ships a Material Symbols catalog. Hand-written SVG
paths in the shell were a stopgap; the real set gives correct optical sizes, rounded
corners and a consistent drawing. The icons land between ICONS:START / ICONS:END in
_shell_shim.js, so the app stays a single file with no runtime fetch.

    python tools/make_icons.py            # regenerate
    python tools/make_icons.py --check    # fail when the shim is stale
"""
import argparse
import gzip
import json
import os
import sys

CATALOG = r"C:\Program Files\Iconset\resources\catalog\material-symbols.json.gz"
HERE = os.path.dirname(os.path.abspath(__file__))
SHIM = os.path.join(os.path.dirname(HERE), "app", "src", "main", "assets", "www", "_shell_shim.js")

# shell name -> Material Symbols name
WANT = {
    "home": "home-rounded",
    "list": "queue-music-rounded",
    "sliders": "tune-rounded",
    "vis": "graphic-eq-rounded",
    "gear": "settings-rounded",
    "play": "play-arrow-rounded",
    "pause": "pause-rounded",
    "stop": "stop-rounded",
    "more": "more-vert-rounded",
    "close": "close-rounded",
    "chev": "chevron-right-rounded",
    "book": "menu-book-rounded",
    "shield": "verified-user-rounded",
    "info": "info-rounded",
    "down": "download-rounded",
    "moon": "bedtime-rounded",
    "focus": "center-focus-strong-rounded",
    "relax": "spa-rounded",
    "sun": "sunny-rounded",
    "theme": "dark-mode-rounded",
    "wave": "waves-rounded",
}

START = "/* ICONS:START */"
END = "/* ICONS:END */"


def build():
    d = json.load(gzip.open(CATALOG, "rt", encoding="utf-8"))
    icons = d["icons"]
    out, missing = {}, []
    for shell, mat in WANT.items():
        node = icons.get(mat) or icons.get(mat.replace("-rounded", ""))
        if not node:
            missing.append(mat)
            continue
        body = node["body"]
        body = body.replace('fill="currentColor"', "").replace("  ", " ").strip()
        out[shell] = body
    return out, missing


def block(icons):
    lines = [START, "  /* Generated by tools/make_icons.py from the Material Symbols catalog in the",
             "     local Iconset library. Filled glyphs, 24x24, inherited colour. */",
             "  var IC = {"]
    for k in sorted(icons):
        lines.append('    "%s": %s,' % (k, json.dumps(icons[k])))
    lines[-1] = lines[-1].rstrip(",")
    lines += ["  };", END]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    icons, missing = build()
    if missing:
        print("missing from the catalog: %s" % ", ".join(missing))
        return 1
    src = open(SHIM, encoding="utf-8").read()
    i, j = src.index(START), src.index(END) + len(END)
    new = src[:i] + block(icons) + src[j:]
    if a.check:
        if new != src:
            print("shim icon block is stale - run tools/make_icons.py")
            return 1
        print("icons in sync (%d)" % len(icons))
        return 0
    open(SHIM, "w", encoding="utf-8", newline="\n").write(new)
    print("wrote %d icons" % len(icons))
    return 0


if __name__ == "__main__":
    sys.exit(main())
